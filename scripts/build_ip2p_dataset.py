#!/usr/bin/env python3
"""Build pseudo-paired InstructPix2Pix data from film-domain scans.

The official diffusers IP2P script expects:

- input_image: original image before edit
- edited_image: target image after edit
- edit_prompt: instruction text

Real digital-to-film pairs are not available in this repo, so this builder
creates a conservative pseudo-pair: the film scan is the edited target, and a
deterministically color-corrupted version is the input image.

Example:
  python scripts/build_ip2p_dataset.py --style portra_400 --max-per-style 200
  python scripts/build_ip2p_dataset.py --all --max-per-style 200 --overwrite
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import shutil
from pathlib import Path

import numpy as np
from PIL import Image, ImageEnhance


ROOT = Path(__file__).resolve().parents[1]
IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp"}

EDIT_PROMPTS = {
    "ektar_100": "Apply a Kodak Ektar 100 film look with vivid saturated colors, crisp contrast, and ultra fine grain.",
    "hp5": "Apply an Ilford HP5 Plus black and white film look with classic grain and rich tonality.",
    "portra_400": "Apply a Kodak Portra 400 film look with warm natural skin tones, soft contrast, and fine grain.",
    "portra_800": "Apply a Kodak Portra 800 film look with warm colors, moderate grain, and natural contrast.",
    "tri_x_400": "Apply a Kodak Tri-X 400 black and white film look with strong contrast and classic grain.",
    "velvia_50": "Apply a Fujifilm Velvia 50 slide film look with vivid saturated colors, deep shadows, and fine grain.",
    "vision3_250d": "Apply a Kodak Vision3 250D cinematic daylight film look with soft highlight rolloff and fine grain.",
    "vision3_500t": "Apply a Kodak Vision3 500T cinematic tungsten film look with warm shadows and visible film grain.",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Create local pseudo-paired IP2P datasets.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--style", help="Single style to build, e.g. portra_400.")
    group.add_argument("--all", action="store_true", help="Build all styles present in the manifest.")
    parser.add_argument(
        "--manifest",
        type=Path,
        default=ROOT / "data" / "processed" / "manifest.jsonl",
        help="Manifest generated by scripts/build_data_manifest.py.",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        default=ROOT / "data" / "ip2p_train",
        help="Output root for generated datasets.",
    )
    parser.add_argument("--max-per-style", type=int, default=200)
    parser.add_argument("--val-fraction", type=float, default=0.1)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--jpeg-quality", type=int, default=92)
    parser.add_argument("--link-mode", choices=["hardlink", "copy"], default="hardlink")
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def to_abs(path: Path) -> Path:
    return path if path.is_absolute() else ROOT / path


def load_records(manifest: Path) -> dict[str, list[dict]]:
    manifest = to_abs(manifest)
    if not manifest.exists():
        raise FileNotFoundError(f"Manifest not found: {manifest}")

    by_style: dict[str, list[dict]] = {}
    with manifest.open("r", encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            record = json.loads(line)
            path = to_abs(Path(record["path"]))
            if record.get("split") != "train":
                continue
            if path.suffix.lower() not in IMAGE_SUFFIXES or not path.exists():
                continue
            style = record["style"]
            by_style.setdefault(style, []).append({**record, "abs_path": path})
    return by_style


def stable_rng(path: Path, seed: int) -> np.random.Generator:
    digest = hashlib.sha256(f"{seed}:{path.as_posix()}".encode("utf-8")).digest()
    return np.random.default_rng(int.from_bytes(digest[:8], "little"))


def make_input_image(image: Image.Image, rng: np.random.Generator) -> Image.Image:
    """Create a pseudo-digital source image from a film target image."""
    img = image.convert("RGB")

    # Nudge away from the film target without destroying scene structure.
    saturation = float(rng.uniform(0.72, 1.18))
    contrast = float(rng.uniform(0.82, 1.18))
    brightness = float(rng.uniform(0.90, 1.10))
    img = ImageEnhance.Color(img).enhance(saturation)
    img = ImageEnhance.Contrast(img).enhance(contrast)
    img = ImageEnhance.Brightness(img).enhance(brightness)

    arr = np.asarray(img).astype(np.float32) / 255.0
    wb = rng.uniform(0.88, 1.12, size=(1, 1, 3)).astype(np.float32)
    gamma = float(rng.uniform(0.86, 1.16))
    arr = np.clip(arr * wb, 0.0, 1.0)
    arr = np.power(arr, gamma)

    # Mild denoise/desaturate proxy: pull channels slightly toward luminance.
    luminance = (0.2126 * arr[..., 0] + 0.7152 * arr[..., 1] + 0.0722 * arr[..., 2])[..., None]
    mix = float(rng.uniform(0.04, 0.14))
    arr = arr * (1.0 - mix) + luminance * mix

    return Image.fromarray(np.clip(arr * 255.0, 0, 255).astype(np.uint8), mode="RGB")


def safe_name(path: Path) -> str:
    digest = hashlib.sha1(path.as_posix().encode("utf-8")).hexdigest()[:10]
    return f"{path.stem}_{digest}.jpg"


def link_or_copy(src: Path, dst: Path, mode: str) -> None:
    if dst.exists():
        dst.unlink()
    if mode == "hardlink":
        try:
            os.link(src, dst)
            return
        except OSError:
            pass
    shutil.copy2(src, dst)


def build_style(style: str, records: list[dict], args: argparse.Namespace) -> dict:
    output_root = to_abs(args.output_root)
    style_root = output_root / style
    if style_root.exists() and args.overwrite and not args.dry_run:
        shutil.rmtree(style_root)

    rng = random.Random(args.seed)
    selected = sorted(records, key=lambda record: record["path"])
    rng.shuffle(selected)
    if args.max_per_style > 0:
        selected = selected[: args.max_per_style]

    val_count = round(len(selected) * args.val_fraction)
    val_paths = {record["path"] for record in selected[:val_count]}
    stats = {"style": style, "train": 0, "val": 0, "output": str(style_root)}
    if args.dry_run:
        stats["selected"] = len(selected)
        return stats

    for split in ("train", "val"):
        (style_root / split / "input").mkdir(parents=True, exist_ok=True)
        (style_root / split / "edited").mkdir(parents=True, exist_ok=True)

    metadata_handles = {
        "train": (style_root / "train" / "metadata.jsonl").open("w", encoding="utf-8"),
        "val": (style_root / "val" / "metadata.jsonl").open("w", encoding="utf-8"),
    }

    try:
        for record in selected:
            source = Path(record["abs_path"])
            split = "val" if record["path"] in val_paths else "train"
            name = safe_name(source)
            input_rel = f"input/{name}"
            edited_rel = f"edited/{name}"
            input_path = style_root / split / input_rel
            edited_path = style_root / split / edited_rel

            with Image.open(source) as image:
                input_image = make_input_image(image, stable_rng(source, args.seed))
                input_image.save(input_path, format="JPEG", quality=args.jpeg_quality, optimize=True)
            link_or_copy(source, edited_path, args.link_mode)

            row = {
                "input_image_file_name": input_rel,
                "edited_image_file_name": edited_rel,
                "edit_prompt": EDIT_PROMPTS.get(style, f"Apply a {style} film look."),
                "style": style,
                "source_path": record["path"],
                "source_sha256": record.get("sha256"),
            }
            metadata_handles[split].write(json.dumps(row, ensure_ascii=True) + "\n")
            stats[split] += 1
    finally:
        for handle in metadata_handles.values():
            handle.close()

    return stats


def main() -> int:
    args = parse_args()
    records_by_style = load_records(args.manifest)
    styles = sorted(records_by_style) if args.all else [args.style]
    missing = [style for style in styles if style not in records_by_style]
    if missing:
        raise RuntimeError(f"No manifest records for style(s): {', '.join(missing)}")

    summary = {
        "schema_version": 1,
        "purpose": "pseudo-paired InstructPix2Pix dataset",
        "warning": "Synthetic pseudo-pairs only; replace with real digital/film pairs when available.",
        "max_per_style": args.max_per_style,
        "val_fraction": args.val_fraction,
        "styles": [],
    }
    for style in styles:
        stats = build_style(style, records_by_style[style], args)
        summary["styles"].append(stats)
        print(f"{style}: train={stats.get('train', 0)} val={stats.get('val', 0)} output={stats['output']}")

    if not args.dry_run:
        output_root = to_abs(args.output_root)
        output_root.mkdir(parents=True, exist_ok=True)
        summary_path = output_root / "summary.json"
        summary_path.write_text(json.dumps(summary, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
        print(f"Summary: {summary_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
